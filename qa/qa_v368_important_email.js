'use strict';
const fs=require('fs');
let passed=0,failed=0;
function check(name,ok){if(ok){passed++;console.log('PASS',name)}else{failed++;console.error('FAIL',name)}}
const server=fs.readFileSync('server/server.js','utf8');
const mail=fs.readFileSync('server/v368-critical-email.js','utf8');
const settings=fs.readFileSync('server/v319.js','utf8');
const access=fs.readFileSync('server/v316.js','utf8');
const payroll=fs.readFileSync('server/v359-payroll.js','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
check('version 30.68.0',pkg.version==='30.68.0');
check('critical email module installed',server.includes("require('./v368-critical-email').install"));
check('notify hook preserves in-app then promotes',server.includes('criticalEmailV368?.notifyEvent?.(row)'));
check('deduplication table present',mail.includes('system_critical_email_events')&&mail.includes('UNIQUE(event_key,user_id)'));
check('email globally opt-in',mail.includes('!cfg.email_enabled'));
check('critical-only guard',mail.includes('cfg.critical_email_only===false'));
check('high-risk approval filter',mail.includes('highRiskApproval'));
check('finance correction classification',mail.includes('Finance / Accounting Correction'));
check('payroll account classification',mail.includes('Payroll / Bank Account'));
check('security classification',mail.includes('Security / Access'));
check('critical system classification',mail.includes('Critical System'));
check('routine low stock is not email classified',!mail.toLowerCase().includes("low stock"));
check('routine overdue task is not email classified',!mail.toLowerCase().includes("overdue task"));
check('existing smtp sender reused',settings.includes('async function sendSystemEmail'));
check('important email settings exist',settings.includes('email_high_risk_approvals')&&settings.includes('email_system_critical'));
check('access changes create security notification',access.includes("'security_event'"));
check('payroll decisions notify requester',payroll.includes('Employee payment account approved')&&payroll.includes('Employee payment account rejected'));
check('backup failure critical notification',settings.includes("'system_critical'")&&settings.includes("'Backup failed'"));
check('email failure cannot block transaction',mail.includes("Promise.resolve().then(()=>promote(n))"));
console.log(`V30.68 QA: ${passed} passed, ${failed} failed`);process.exit(failed?1:0);
