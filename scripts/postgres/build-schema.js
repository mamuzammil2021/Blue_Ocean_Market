'use strict';
// Offline generation from checked-in schema metadata. No SQL translation runs
// in the web process. Unsupported SQLite constructs stop generation.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {identifier:q}=require('../../server/postgres/connection');
const root=path.resolve(__dirname,'../..');
const catalog=require('../../server/postgres/catalog-v306950.json');
const digest=s=>crypto.createHash('sha256').update(s).digest('hex');
const name=s=>s.length<=63?s:s.slice(0,46)+'_'+digest(s).slice(0,16);
const table=n=>`bom.${q(n)}`;

function checks(sql){
  const found=[];
  for(let i=0;i<sql.length;){
    if(sql[i]==="'"||sql[i]==='"'||sql[i]==='`'){
      const quote=sql[i++];
      while(i<sql.length){if(sql[i++]===quote){if(sql[i]===quote)i++;else break}}
    }else if(sql.slice(i,i+2)==='--'){
      i=sql.indexOf('\n',i);if(i<0)break;
    }else if(sql.slice(i,i+2)==='/*'){
      const end=sql.indexOf('*/',i+2);if(end<0)throw new Error('Unclosed SQL comment');i=end+2;
    }else if(/[A-Za-z_]/.test(sql[i])){
      const start=i++;while(/[A-Za-z_0-9]/.test(sql[i]||'')&&i<sql.length)i++;
      if(sql.slice(start,i).toUpperCase()!=='CHECK')continue;
      while(/\s/.test(sql[i]||'')&&i<sql.length)i++;
      if(sql[i]!=='(')throw new Error('Invalid CHECK expression');
      const begin=i;let depth=0;
      do{
        const c=sql[i++];
        if(c==="'"||c==='"'){
          while(i<sql.length){if(sql[i++]===c){if(sql[i]===c)i++;else break}}
        }else if(c==='(')depth++;else if(c===')')depth--;
      }while(i<sql.length&&depth>0);
      if(depth)throw new Error('Unclosed CHECK expression');
      found.push('CHECK'+sql.slice(begin,i));
    }else i++;
  }
  return found;
}

function generate(){
  const statements=[`-- Generated from the initialized V30.69.50 schema, not from customer rows.
-- Source schema SHA-256: ${catalog.schemaSha256}
-- One database, one application schema. Money/quantity REAL columns become exact
-- NUMERIC without quantization. Existing scaled INTEGER quantities remain BIGINT.
-- Snapshot/date text is intentionally retained byte-for-byte for this migration.
SET LOCAL search_path TO bom,pg_catalog;`];
  for(const t of catalog.tables){
    const primary=t.columns.filter(c=>c.pk).sort((a,b)=>a.pk-b.pk);
    const definitions=t.columns.map(c=>{
      const type={INTEGER:'BIGINT',TEXT:'TEXT',REAL:'NUMERIC'}[c.type];
      if(!type)throw new Error(`Unsupported type ${t.name}.${c.name}: ${c.type}`);
      const identity=primary.length===1&&primary[0].name===c.name&&c.type==='INTEGER';
      let out=`${q(c.name)} ${type}${identity?' GENERATED BY DEFAULT AS IDENTITY':''}${c.notnull?' NOT NULL':''}`;
      if(c.dflt_value!==null){
        if(identity)throw new Error(`Identity column has a default: ${t.name}.${c.name}`);
        const d=c.dflt_value;
        out+=' DEFAULT '+(d.toUpperCase()==='CURRENT_TIMESTAMP'?"to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')":d);
      }
      return out;
    });
    if(primary.length)definitions.push(`PRIMARY KEY (${primary.map(c=>q(c.name)).join(',')})`);
    definitions.push(...checks(t.sql));
    for(const index of t.indexes.filter(i=>i.origin==='u')){
      const columns=index.columns.filter(c=>c.key);
      if(columns.some(c=>c.cid<0||c.coll!=='BINARY'))throw new Error(`Unsupported unique key ${index.name}`);
      definitions.push(`UNIQUE (${columns.map(c=>q(c.name)).join(',')})`);
    }
    statements.push(`CREATE TABLE ${table(t.name)} (\n  ${definitions.join(',\n  ')}\n);`);
  }
  for(const t of catalog.tables){
    const groups=Map.groupBy(t.foreignKeys,f=>f.id);
    for(const [id,keys] of groups){
      keys.sort((a,b)=>a.seq-b.seq);
      const fk=keys[0];
      if(!catalog.tables.some(t=>t.name===fk.table))throw new Error(`Missing foreign-key table ${fk.table}`);
      const target=fk.to?keys.map(k=>k.to):catalog.tables.find(t=>t.name===fk.table).columns.filter(c=>c.pk).sort((a,b)=>a.pk-b.pk).map(c=>c.name);
      if(target.length!==keys.length)throw new Error(`Ambiguous foreign key ${t.name}.${id}`);
      const action=a=>{if(!['NO ACTION','RESTRICT','CASCADE','SET NULL','SET DEFAULT'].includes(a))throw new Error('Unknown FK action');return a};
      statements.push(`ALTER TABLE ${table(t.name)} ADD CONSTRAINT ${q(name(`${t.name}_fk_${id}`))} FOREIGN KEY (${keys.map(k=>q(k.from)).join(',')}) REFERENCES ${table(fk.table)} (${target.map(q).join(',')}) ON UPDATE ${action(fk.on_update)} ON DELETE ${action(fk.on_delete)} DEFERRABLE INITIALLY IMMEDIATE;`);
    }
    for(const index of t.indexes.filter(i=>i.sql)){
      if(/\b(COLLATE|IFNULL|STRFTIME|DATETIME|JSON_\w*)\b/i.test(index.sql))throw new Error(`Index needs manual conversion: ${index.name}`);
      // This index explicitly trims bank-reference whitespace. PostgreSQL uses
      // chr()/btrim(); char() is a type keyword, not SQLite's codepoint function.
      const indexSql=index.name==='idx_pink_fx_reference'
        ? "CREATE UNIQUE INDEX idx_pink_fx_reference ON pink_fx_transactions(company_account_id,lower(btrim(reference))) WHERE length(btrim(reference,chr(9)||chr(10)||chr(13)||' '))>0 AND status='Active'"
        : index.sql;
      const match=indexSql.match(/^CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF NOT EXISTS\s+)?(?:"[^"]+"|\w+)\s+ON\s+(?:"[^"]+"|\w+)([\s\S]+)$/i);
      if(!match)throw new Error(`Unrecognized index ${index.name}`);
      statements.push(`CREATE ${match[1]||''}INDEX ${q(name(index.name))} ON ${table(t.name)}${match[2].replace(/;\s*$/,'')};`);
    }
  }
  for(const view of catalog.views)statements.push(view.sql.replace(/^CREATE VIEW (\w+)/i,(_,n)=>`CREATE VIEW ${table(n)}`)+';');
  return statements.join('\n\n')+'\n';
}

if(require.main===module){
  const output=path.join(root,'server/postgres/migrations/001-full-schema.sql');
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output,generate());
  console.log(JSON.stringify({tables:catalog.tables.length,columns:catalog.tables.reduce((n,t)=>n+t.columns.length,0),sha256:digest(fs.readFileSync(output))}));
}
module.exports={generate,checks};
