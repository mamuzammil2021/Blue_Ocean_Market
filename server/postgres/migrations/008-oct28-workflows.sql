CREATE TABLE bom.warehouse_transfers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 business_unit_id BIGINT NOT NULL REFERENCES bom.business_units(id),
 idempotency_key TEXT NOT NULL, payload_hash TEXT NOT NULL,
 stock_type TEXT NOT NULL CHECK(stock_type IN ('raw','finished')),
 stock_id BIGINT NOT NULL, lot_id BIGINT, production_batch_id BIGINT,
 from_location_id BIGINT REFERENCES bom.pink_salt_storage_locations(id),
 to_location_id BIGINT NOT NULL REFERENCES bom.pink_salt_storage_locations(id),
 quantity NUMERIC NOT NULL CHECK(quantity>0), movement_date TEXT NOT NULL,
 reason TEXT NOT NULL, created_by BIGINT NOT NULL REFERENCES bom.users(id),
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 UNIQUE(business_unit_id,idempotency_key)
);
