CREATE TABLE bom._pg_maintenance(
 id UUID PRIMARY KEY,action TEXT NOT NULL,backup_name TEXT NOT NULL,
 backup_sha256 TEXT NOT NULL,actor_json JSONB NOT NULL,reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS bom._pg_imports(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,schema_sha256 TEXT NOT NULL,
 report_json JSONB NOT NULL,imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE OR REPLACE FUNCTION bom.queue_finance_sync() RETURNS trigger
LANGUAGE plpgsql SET search_path TO bom,pg_catalog AS $fn$
BEGIN
 INSERT INTO bom.accounting_sync_queue(finance_entry_id,queued_at,attempts,last_error)
 VALUES(NEW.id,bom.utc_now(),0,'')
 ON CONFLICT(finance_entry_id) DO UPDATE SET queued_at=EXCLUDED.queued_at,last_error='',
   attempts=CASE WHEN current_setting('bom.internal_sync',true)='on' THEN accounting_sync_queue.attempts ELSE 0 END;
 RETURN NEW;
END
$fn$;
